#!/usr/bin/env node
// api-scan.js: builds apis/<repo>.md, the list of API endpoints a repo calls (frontend) or serves (backend).
// Usage: node bin/api-scan.js [repo ...]   (no args = every repo in workspace.md)
// Reads source files only. Skips node_modules, build output and every .env file.
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const SKIP_DIRS = new Set(["node_modules", ".next", "dist", "build", "out", ".git", "coverage", ".expo", "test-results", "playwright-report", ".turbo"]);
const EXT = /\.(js|jsx|ts|tsx|mjs|cjs)$/;
const METHODS = "get|post|put|patch|delete";

function walk(dir, files = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.name.startsWith(".env") || SKIP_DIRS.has(e.name)) continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, files);
    else if (EXT.test(e.name) && !/\.(test|spec)\./.test(e.name)) files.push(p);
  }
  return files;
}

function scanRepo(repo) {
  const dir = path.join(root, repo);
  const calls = new Map(); // "METHOD path" -> {method, path, base, refs[]}
  const bases = new Map(); // env var -> count
  const add = (method, p, base, ref) => {
    p = p.replace(/\$\{[^}]+\}/g, ":param").replace(/\?.*$/, "");
    if (!p.startsWith("/") && !/^https?:/.test(p)) p = "/" + p;
    const key = `${method} ${p}`;
    if (!calls.has(key)) calls.set(key, { method, path: p, base, refs: [] });
    const c = calls.get(key);
    if (c.refs.length < 3) c.refs.push(ref);
  };

  for (const file of walk(dir)) {
    const rel = path.relative(dir, file);
    const lines = fs.readFileSync(file, "utf8").split("\n");
    let controller = null;
    lines.forEach((line, i) => {
      const ref = `${rel}:${i + 1}`;
      for (const m of line.matchAll(/process\.env\.([A-Z0-9_]*(?:API|URL|BASE|HOST)[A-Z0-9_]*)/g)) bases.set(m[1], (bases.get(m[1]) || 0) + 1);

      // axios-style client: fooInstance.get("/x"), api.post(`/y`)
      for (const m of line.matchAll(new RegExp(`([A-Za-z_$][\\w$]*)\\.(${METHODS})\\(\\s*[\`'"]([^\`'"]{2,160})`, "g"))) {
        if (!/instance|axios|api|client|http|request/i.test(m[1])) continue;
        if (/^(user-agent|referer|content-type)$/i.test(m[3])) continue;
        add(m[2].toUpperCase(), m[3], m[1], ref);
      }
      // fetch(`${process.env.X}/path`, {method}) or fetch("https://host/path")
      const f = line.match(/fetch\(\s*[`'"](?:\$\{(?:process\.env\.)?([A-Z0-9_]+)\})?([^`'"]{2,160})/);
      if (f) {
        const method = (lines.slice(i, i + 6).join(" ").match(/method:\s*[`'"](\w+)/) || [, "GET"])[1].toUpperCase();
        add(method, f[2], f[1] || "url", ref);
      }
      // NestJS: @Controller('x') + @Get('y')
      const ctl = line.match(/@Controller\(\s*(?:[`'"]([^`'"]*)[`'"])?/);
      if (ctl) controller = ctl[1] || "";
      const dec = line.match(new RegExp(`@(${METHODS.replace(/\b(\w)/g, (c) => c.toUpperCase())})\\(\\s*(?:[\`'"]([^\`'"]*)[\`'"])?`));
      if (dec && controller !== null) add(dec[1].toUpperCase(), `/${controller}/${dec[2] || ""}`.replace(/\/+/g, "/").replace(/(.)\/$/, "$1"), "serves", ref);
      // Express: router.get('/x', ...)
      const ex = line.match(new RegExp(`\\b(router|app)\\.(${METHODS})\\(\\s*[\`'"](/[^\`'"]*)`));
      if (ex) add(ex[2].toUpperCase(), ex[3], "serves", ref);
    });
  }

  if (fs.existsSync(path.join(dir, "artisan"))) scanLaravel(dir, add);

  const list = [...calls.values()].sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
  const gets = list.filter((c) => c.method === "GET").length;
  const serves = list.some((c) => c.base === "serves");
  const out = [
    `# API catalog: ${repo}`,
    "",
    `_Generated by \`node bin/api-scan.js ${repo}\` on ${new Date().toISOString().slice(0, 10)}. Regenerate after backend changes; hand notes go in the Notes section at the end (kept)._`,
    "",
    `- Role: ${serves ? "**serves** these endpoints (backend)" : "**calls** these endpoints (client)"}`,
    `- Endpoints: ${list.length} (${gets} GET = usable by \`bin/api-get\`)`,
    `- Base URL env vars used in code: ${[...bases].sort((a, b) => b[1] - a[1]).map(([k, n]) => `\`${k}\` (${n})`).join(", ") || "none"}`,
    "",
    "| Method | Path | Base / client | Where |",
    "|---|---|---|---|",
    ...list.map((c) => `| ${c.method} | \`${c.path}\` | ${c.base} | ${c.refs.join("<br>")} |`),
  ];
  const file = path.join(root, "apis", `${repo}.md`);
  const notes = fs.existsSync(file) ? (fs.readFileSync(file, "utf8").split("\n## Notes")[1] ?? null) : null;
  out.push("", "## Notes" + (notes ?? "\n\n- (hand-written: auth scope, admin-only endpoints, pagination param, which fields are personal data)\n"));
  fs.writeFileSync(file, out.join("\n"));
  return `${repo}: ${list.length} endpoints (${gets} GET)${serves ? ", backend" : ""}`;
}

// Laravel: follows Route::prefix('x')->...->group(function / base_path('routes/…php')) nesting from
// routes/api.php (served under /api) and routes/web.php, and records each Route::get/post/… with its full path.
function scanLaravel(dir, add) {
  const seen = new Set();
  const read = (rel, prefix, base) => {
    const file = path.join(dir, rel);
    if (seen.has(file + prefix) || !fs.existsSync(file)) return;
    seen.add(file + prefix);
    const lines = fs.readFileSync(file, "utf8").split("\n");
    const stack = [prefix];
    let pending = null; // prefix of a Route::prefix(...) chain not yet closed by ->group(
    lines.forEach((line, i) => {
      if (/^\s*(\/\/|#|\*)/.test(line)) return;
      const cur = stack[stack.length - 1];
      const pre = line.match(/Route::prefix\(\s*['"]([^'"]*)['"]/) || line.match(/['"]prefix['"]\s*=>\s*['"]([^'"]*)['"]/);
      if (pre) pending = `${cur}/${pre[1]}`;
      else if (/Route::(middleware|group|name|domain)\b/.test(line) && pending === null) pending = cur;
      const sub = line.match(/->group\(\s*base_path\(\s*['"]([^'"]+)['"]/);
      if (sub) { read(sub[1], pending ?? cur, base); pending = null; return; }
      if (/group\(\s*(\[[^\]]*\]\s*,\s*)?function/.test(line)) { stack.push(pending ?? cur); pending = null; }
      const r = line.match(/Route::(get|post|put|patch|delete|match|any)\(\s*(\[[^\]]*\]\s*,\s*)?['"]([^'"]*)['"]/i);
      if (r) {
        const methods = r[1].toLowerCase() === "match" ? (r[2] || "").match(/get|post|put|patch|delete/gi) || ["ANY"] : [r[1]];
        for (const m of methods) add(m.toUpperCase(), `${base}${cur}/${r[3]}`.replace(/\/+/g, "/").replace(/(.)\/$/, "$1"), "serves", `${rel}:${i + 1}`);
      }
      if (/^\s*\}\s*\)\s*;/.test(line) && stack.length > 1) stack.pop();
    });
  };
  read("routes/api.php", "", "/api");
  read("routes/web.php", "", "");
}

let repos = process.argv.slice(2);
if (!repos.length) repos = fs.readdirSync(root).filter((n) => !n.startsWith(".") && fs.existsSync(path.join(root, n, ".git")));
fs.mkdirSync(path.join(root, "apis"), { recursive: true });
for (const r of repos) console.log(scanRepo(r));
